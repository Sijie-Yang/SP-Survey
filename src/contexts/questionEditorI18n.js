function settingName(path) {
  return path.split('.').map(part => {
    const match = part.match(/^(\w+)\[(\d+)\]$/);
    return match ? `第 ${Number(match[2]) + 1} 个${settingNames[match[1]] || match[1]}` : (settingNames[part] || part);
  }).join('的');
}
export function questionSettingErrorText(message, language) {
  if (language !== 'zh') return message;
  const patterns = [
    [/^(.+) must be a finite number\.$/, m => `${settingName(m[1])}必须是有效数字。`],
    [/^(.+) must not exceed (.+)\.$/, m => `${settingName(m[1])}不能大于${settingName(m[2])}。`],
    [/^(.+) must be a non-negative integer\.$/, m => `${settingName(m[1])}必须是大于或等于 0 的整数。`],
    [/^(.+) must be a positive number\.$/, m => `${settingName(m[1])}必须是大于 0 的数字。`],
    [/^(.+) needs a stable, non-empty ID\.$/, m => `${settingName(m[1])}需要填写固定且非空的标识。`],
    [/^(.+): duplicate ID "(.*)"\.$/, m => `${settingName(m[1])}中存在重复标识“${m[2]}”。`],
  ];
  const fixed = {
    'Scale minimum must be less than its maximum.': '量表最小值必须小于最大值。',
    'Dimension minimum must be less than its effective maximum.': '维度最小值必须小于该维度实际使用的最大值。',
    'Dimension step must be positive.': '维度步长必须大于 0。',
  };
  if (fixed[message]) return fixed[message];
  for (const [pattern, format] of patterns) { const match = message.match(pattern); if (match) return format(match); }
  return message;
}
